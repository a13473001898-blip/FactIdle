// ================== 🌟 动态计算 1.5倍对齐 体积算法 ==================

const 产物找配方字典 = {};
for (const 配方ID in 配方配置) {
    const 配方 = 配方配置[配方ID];
    if (配方.输出) {
        for (const 产物 of 配方.输出) {
            产物找配方字典[产物.id] = 配方;
        }
    }
}

function 计算字节(裸字节) {
    if (裸字节 <= 1) return 1;
    if (裸字节 <= 2) return 2;
    const p = Math.pow(2, Math.floor(Math.log2(裸字节)));
    if (裸字节 === p) return p;
    const mid = p * 1.5;
    if (裸字节 <= mid) return mid;
    return p * 2;
}

function 动态计算物品字节(物品id, 递归路径 = new Set()) {
    const 物品 = 物品配置[物品id];
    if (物品.字节 !== undefined) return 物品.字节;

    if (递归路径.has(物品id)) return 1;
    
    递归路径.add(物品id);

    const 来源配方 = 产物找配方字典[物品id];
    let 最终计算结果 = 1;

    if (!来源配方 || !来源配方.输入 || 来源配方.输入.length === 0) {
        最终计算结果 = 1; // 基础资源默认 1
    } else {
        let 总原料裸字节 = 0;
        for (const 原料 of 来源配方.输入) {
            const 原料单体字节 = 动态计算物品字节(原料.id, 递归路径);
            总原料裸字节 += 原料单体字节 * 原料.数量;
        }

        const 当前物品产出量 = 来源配方.输出.find(out => out.id === 物品id)?.数量 || 1;
        const 裸字节 = 总原料裸字节 / 当前物品产出量;
        最终计算结果 = 计算字节(裸字节);
    }
    递归路径.delete(物品id);
    物品.字节 = 最终计算结果;
    return 最终计算结果;
}

// 在冻结之前，统一赋体积
for (const 物品id in 物品配置) {
    if (物品配置[物品id].字节 === undefined) {
        物品配置[物品id].字节 = 动态计算物品字节(物品id);
    }
}

