function 冻结对象(对象) {
    if (对象 === null || typeof 对象 !== 'object') return 对象;
    for (const 键 of Object.keys(对象)) {
        const 值 = 对象[键]
        if (值 && typeof 值 === 'object' && !Object.isFrozen(值)) 冻结对象(值)
    }
    return Object.freeze(对象)
}

