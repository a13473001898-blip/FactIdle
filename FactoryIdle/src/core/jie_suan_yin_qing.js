function 速率数据模板() {
    return { 产出: 0, 消耗: 0, 需求: 0, 净值: 0, 理论需求: 0, 理论产出: 0 };
}

function 合并账单(总账单, 分账单) {
    for (const 物品id in 分账单) {
        if (!总账单[物品id]) 总账单[物品id] = 速率数据模板();
        const 单项 = 分账单[物品id];
        总账单[物品id].产出 += 单项.产出 || 0;
        总账单[物品id].消耗 += 单项.消耗 || 0;
        总账单[物品id].需求 += 单项.需求 || 0;
        总账单[物品id].理论需求 += 单项.理论需求 || 0;
        总账单[物品id].理论产出 += 单项.理论产出 || 0;
    }
}

// ==========================================
// 🌟 核心调度中心：多殖民地分布式结算
// ==========================================
export function 执行全局速率结算() {
    const 殖民地系统 = use殖民地系统();
    const 科技系统 = use科技系统();
    
    // 每次物理帧结算前，重置全球科技进度缓存
    科技系统.当前研发.每秒进度比例 = 0;

    // 大循环：遍历所有已发现的星球/基地
    for (const colony of 殖民地系统.列表) {
        const cid = colony.id;
        const 临时总账单 = {};
        for (const key in 获取所有物品列表()) {
            临时总账单[key] = 速率数据模板();
        }

        // 1. 结算本地能源
        const { 新能源数据, 能源账单 } = 计算本地能源(cid, colony.环境);
        use能源模块().写入能源数据(cid, 新能源数据, 能源账单);

        // 2. 结算本地配方账单 (核心：支持多生产线遍历)
        const 配方账单 = 计算本地配方账单(cid, colony.资源丰度);

        // 3. 结算本地科技系统 (计算该星球对全球科研的贡献)
        const { 科技账单, 本地科研进度贡献 } = 计算本地科技账单(cid);
        科技系统.当前研发.每秒进度比例 += 本地科研进度贡献;

        // 4. 合并账单
        合并账单(临时总账单, 配方账单);
        合并账单(临时总账单, 能源账单);
        合并账单(临时总账单, 科技账单);

        // 5. 写入最终净值
        for (const 物品id in 临时总账单) {
            const item = 临时总账单[物品id];
            item.净值 = item.产出 - item.消耗;
        }
        use全局速率().写入殖民地速率(cid, 临时总账单);
    }
}

// --- 科技系统计算 (支持生产线层级) ---
function 计算本地科技账单(cid) {
    const 账单 = {};
    const 研发数据 = use科技系统().当前研发;
    const 内存满足率 = use计算机系统().内存满足率(cid); 

    if (!研发数据.科技ID) return { 科技账单: 账单, 本地科研进度贡献: 0 };

    const 科技 = 获取科技数据(研发数据.科技ID);
    const 配方分配 = use配方分配();
    const 能源模块 = use能源模块();
    
    // 🌟 修复：科技目前默认分配在 'default' 生产线
    const 科研分配 = 配方分配.查询建筑(全局常量.默认产线ID, 'ke_yan', cid);
    let 最大总产出 = 0;

    for (const 建筑id in 科研分配) {
        const 分配数据 = 科研分配[建筑id];
        if (分配数据.状态 === '运行' && 分配数据.数量 > 0) {
            const 建筑数据 = 获取建筑数据(建筑id);
            const 基础速度 = 建筑数据?.速度 || 1;
            let 能源满足率 = 1;
            if (建筑数据.能源类型 && 建筑数据.能源类型 !== '无') {
                能源满足率 = 能源模块.查询满足率(建筑数据.能源类型, cid);
            }
            最大总产出 += 分配数据.数量 * 基础速度 * 能源满足率 * 内存满足率;
        }
    }

    if (最大总产出 === 0) return { 科技账单: 账单, 本地科研进度贡献: 0 };

    const 理论每秒进度 = 科技.耗时 === 0 ? Infinity : 最大总产出 / 科技.耗时;
    const 库存 = use库存();
    let 实际满足率 = 1;

    for (const 投入 of 科技.投入) {
        const 理论需求速率 = 理论每秒进度 * 投入.数量;
        if (理论需求速率 > 0) {
            const 当前库存 = 库存.查询库存(投入.id, cid) || 0;
            const 最大可支撑比例 = 当前库存 / 理论需求速率;
            if (最大可支撑比例 < 实际满足率) 实际满足率 = 最大可支撑比例;
        }
    }
    
    实际满足率 = Math.min(实际满足率, 1);
    const 实际每秒进度 = 理论每秒进度 * 实际满足率;

    for (const 投入 of 科技.投入) {
        const 理论需求 = 理论每秒进度 * 投入.数量;
        const 实际消耗 = 实际每秒进度 * 投入.数量;
        账单[投入.id] = { 产出: 0, 消耗: 实际消耗, 需求: 理论需求, 净值: -实际消耗 };
    }
    return { 科技账单: 账单, 本地科研进度贡献: 实际每秒进度 };
}

// --- 配方系统计算 (🌟 修复：三层嵌套遍历) ---
function 计算本地配方账单(cid, 资源丰度) {
    const 配方分配 = use配方分配();
    const 临时速率表 = {};
    const 库存 = use库存();
    const 能源模块 = use能源模块();
    const 内存满足率 = use计算机系统().内存满足率(cid);

    for (const key in 获取所有物品列表()) {
        临时速率表[key] = { 产出: 0, 消耗: 0, 需求: 0, 净值: 0, 理论需求: 0, 理论产出: 0 };
    }

    // 1. 收集理论极值
    const 殖民地全部线 = 配方分配.查询殖民地全部(cid); //
    for (const lineId in 殖民地全部线) {
        const 生产线数据 = 殖民地全部线[lineId];
        for (const 配方ID in 生产线数据) {
            const 分配情况 = 生产线数据[配方ID];
            const 当前配方 = 获取配方数据(配方ID);
            if (!当前配方 || 当前配方.时间 === 0) continue;

            let 当前配方丰度倍率 = 1;
            if (当前配方.类型 === '采集' && 当前配方.输出?.length > 0) {
                当前配方丰度倍率 = 资源丰度[当前配方.输出[0].id] ?? 1;
            }

            for (const 建筑ID in 分配情况) {
                if (分配情况[建筑ID].状态 !== '运行') continue;

                const 建筑 = 获取建筑数据(建筑ID);
                const 数量 = 分配情况[建筑ID].数量;
                const 能源满足 = 建筑.能源类型 && 建筑.能源类型 !== '无' ? 能源模块.查询满足率(建筑.能源类型, cid) : 1;
                const 机器实际最大速度 = 数量 * (建筑?.速度 || 0) * 能源满足 * 内存满足率;
                const 每秒最大批次 = 机器实际最大速度 / 当前配方.时间;

                if (当前配方.输入) {
                    for (const 原料 of 当前配方.输入) {
                        临时速率表[原料.id].理论需求 += 每秒最大批次 * 原料.数量;
                    }
                }
                if (当前配方.输出) {
                    for (const 产物 of 当前配方.输出) {
                        临时速率表[产物.id].理论产出 += 每秒最大批次 * 产物.数量 * 当前配方丰度倍率;
                    }
                }
            }
        }
    }

    // 2. 多轮迭代消除“虚假承诺”
    const 迭代次数 = 8;
    for (let i = 0; i < 迭代次数; i++) {
        const 物品满足率表 = {};
        for (const 物品ID in 临时速率表) {
            const 数据 = 临时速率表[物品ID];
            const 当前库存 = 库存.查询库存(物品ID, cid) || 0;
            const 预估产出 = (i === 0) ? 数据.理论产出 : 数据.产出;
            const 总供应能力 = 预估产出 + 当前库存;
            物品满足率表[物品ID] = 数据.理论需求 === 0 ? 1 : Math.min(总供应能力 / 数据.理论需求, 1);
        }

        for (const 物品ID in 临时速率表) {
            临时速率表[物品ID].产出 = 0;
            临时速率表[物品ID].消耗 = 0;
            临时速率表[物品ID].需求 = 0;
        }

        for (const lineId in 殖民地全部线) {
            const 生产线数据 = 殖民地全部线[lineId];
            for (const 配方ID in 生产线数据) {
                const 分配情况 = 生产线数据[配方ID];
                const 当前配方 = 获取配方数据(配方ID);
                if (!当前配方) continue;
                
                let 当前配方丰度倍率 = 1;
                if (当前配方.类型 === '采集' && 当前配方.输出?.length > 0) {
                    当前配方丰度倍率 = 资源丰度[当前配方.输出[0].id] ?? 1;
                }

                for (const 建筑ID in 分配情况) {
                    if (分配情况[建筑ID].状态 !== '运行') continue;
                    const 建筑 = 获取建筑数据(建筑ID);
                    const 能源满足 = 建筑.能源类型 && 建筑.能源类型 !== '无' ? 能源模块.查询满足率(建筑.能源类型, cid) : 1;
                    const 每秒最大批次 = (分配情况[建筑ID].数量 * 建筑.速度 * 能源满足 * 内存满足率) / 当前配方.时间;

                    let 最短板满足率 = 1;
                    if (当前配方.输入) {
                        for (const 原料 of 当前配方.输入) {
                            最短板满足率 = Math.min(最短板满足率, 物品满足率表[原料.id] || 0);
                        }
                    }

                    const 实际每秒批次 = 每秒最大批次 * 最短板满足率;
                    if (当前配方.输入) {
                        for (const 原料 of 当前配方.输入) {
                            临时速率表[原料.id].需求 += 每秒最大批次 * 原料.数量;
                            临时速率表[原料.id].消耗 += 实际每秒批次 * 原料.数量;
                        }
                    }
                    if (当前配方.输出) {
                        for (const 产物 of 当前配方.输出) {
                            临时速率表[产物.id].产出 += 实际每秒批次 * 产物.数量 * 当前配方丰度倍率;
                        }
                    }
                }
            }
        }
    }
    return 临时速率表;
}

// --- 能源系统计算 (🌟 修复：产出查询增加生产线遍历) ---
function 计算本地能源(cid, 环境) {
    const 消耗清单 = {};
    const 热能数据 = 结算热能(消耗清单, cid);
    const 蒸汽数据 = 结算蒸汽(消耗清单, 热能数据.满足率, cid);
    const 电力数据 = 结算电力(消耗清单, 蒸汽数据.满足率, cid, 环境);
    return { 新能源数据: { 热能: 热能数据, 蒸汽: 蒸汽数据, 电力: 电力数据 }, 能源账单: 消耗清单 };
}

function 计算指定能源总产出(产出物品ID, 上一级满足率, cid, 环境 = null) {
    const 内存满足率 = use计算机系统().内存满足率(cid);
    const 配方分配 = use配方分配();
    let 产出总计 = 0;
    
    const 殖民地全部线 = 配方分配.查询殖民地全部(cid);
    for (const lineId in 殖民地全部线) {
        const 生产线数据 = 殖民地全部线[lineId];
        for (const 配方ID in 生产线数据) {
            const 配方 = 获取配方数据(配方ID);
            const 目标输出 = 配方?.输出?.find(out => out.id === 产出物品ID);
            if (目标输出) {
                const 机器分配情况 = 生产线数据[配方ID];
                for (const 建筑ID in 机器分配情况) {
                    const 状态 = 机器分配情况[建筑ID];
                    if (状态.状态 === '运行') {
                        const 建筑 = 获取建筑数据(建筑ID);
                        产出总计 += 状态.数量 * 建筑.速度 * (目标输出.数量 / 配方.时间) * 上一级满足率 * 内存满足率;
                    }
                }
            }
        }
    }
    return 产出总计;
}


function 计算指定能源总需求(能源类型, cid) {
    const 配方分配 = use配方分配();
    let 需求总计 = 0;
    const 机器列表 = 配方分配.查询指定能源类型建筑(能源类型, cid);
    for (const 建筑id in 机器列表) {
        需求总计 += 机器列表[建筑id].运行数量 * 机器列表[建筑id].能耗;
    }
    return 需求总计;
}


function 结算热能(消耗清单, cid) {
    const 库存 = use库存();
    let 需求总热值 = 计算指定能源总需求('热能', cid);
    let 产出总热值 = 0;
    const 所有物品 = 获取所有物品列表();
    const 燃料列表 = Object.values(所有物品).filter(物品 => 物品.燃料 === true && 物品.热值 > 0);

    if (需求总热值 === 0) return { 产出: 0, 需求: 0, 满足率: 1, 负载率: 1 };

    let 剩余需求 = 需求总热值;
    for (const 燃料 of 燃料列表) {
        if (剩余需求 <= 0) break;
        const 燃料库存 = 库存.查询库存(燃料.id, cid) || 0; // 👈 必须是本地仓库的煤炭
        if (燃料库存 <= 0) continue;
        const 当前燃料能提供的总热值 = 燃料库存 * 燃料.热值;

        if (当前燃料能提供的总热值 >= 剩余需求) {
            const 需要消耗数量 = 剩余需求 / 燃料.热值;
            消耗清单[燃料.id] = { 产出: 0, 消耗: 需要消耗数量, 需求: 需要消耗数量, 净值: -需要消耗数量 };
            产出总热值 += 剩余需求;
            剩余需求 = 0;
        } else {
            消耗清单[燃料.id] = { 产出: 0, 消耗: 燃料库存, 需求: 剩余需求 / 燃料.热值, 净值: -燃料库存 };
            产出总热值 += 当前燃料能提供的总热值;
            剩余需求 -= 当前燃料能提供的总热值;
        }
    }

    const 热能满足率 = 需求总热值 === 0 ? 1 : Math.min(产出总热值 / 需求总热值, 1);

    // UI 显示用的产出速率
    let 燃料产出总热值速率 = 0;
    for (const 燃料 of 燃料列表) {
        const 燃料每秒产出数量 = 计算指定能源总产出(燃料.id, 1, cid);
        燃料产出总热值速率 += 燃料每秒产出数量 * 燃料.热值;
    }
    const 热能负载率 = 燃料产出总热值速率 === 0 ? (需求总热值 > 0 ? Infinity : 0) : 需求总热值 / 燃料产出总热值速率;

    return { 产出: 燃料产出总热值速率, 需求: 需求总热值, 满足率: 热能满足率, 负载率: 热能负载率 };
}

function 结算蒸汽(消耗清单, 热能满足率, cid) {
    const 库存 = use库存();
    const 需求总蒸汽 = 计算指定能源总需求('蒸汽', cid);
    const 蒸汽实时产出 = 计算指定能源总产出(物品ID.蒸汽, 热能满足率, cid);
    const 蒸汽库存 = 库存.查询库存(物品ID.蒸汽, cid) || 0;
    const 可用蒸汽总量 = 蒸汽实时产出 + 蒸汽库存;

    const 蒸汽满足率 = 需求总蒸汽 === 0 ? 1 : Math.min(可用蒸汽总量 / 需求总蒸汽, 1);
    const 蒸汽负载率 = 可用蒸汽总量 === 0 ? (需求总蒸汽 > 0 ? 1 : 0) : 需求总蒸汽 / 蒸汽实时产出;

    if (需求总蒸汽 > 0) {
        const 实际消耗 = Math.min(可用蒸汽总量, 需求总蒸汽);
        消耗清单[物品ID.蒸汽] = { 产出: 0, 消耗: 实际消耗, 需求: 需求总蒸汽, 净值: -实际消耗 };
    }
    return { 产出: 蒸汽实时产出, 需求: 需求总蒸汽, 满足率: 蒸汽满足率, 负载率: 蒸汽负载率 };
}

function 结算电力(消耗清单, 蒸汽满足率, cid, 环境) {
    const 需求总电力 = 计算指定能源总需求('电力', cid);
    const 产出总电力 = 计算指定能源总产出(物品ID.电力, 蒸汽满足率, cid, 环境);
    const 电力满足率 = 需求总电力 === 0 ? 1 : Math.min(产出总电力 / 需求总电力, 1);
    const 电力负载率 = 产出总电力 === 0 ? (需求总电力 > 0 ? 1 : 0) : 需求总电力 / 产出总电力;

    if (需求总电力 > 0) {
        const 实际消耗 = Math.min(产出总电力, 需求总电力);
        消耗清单[物品ID.电力] = { 产出: 0, 消耗: 实际消耗, 需求: 需求总电力, 净值: -实际消耗 };
    }
    return { 产出: 产出总电力, 需求: 需求总电力, 满足率: 电力满足率, 负载率: 电力负载率 };
}