// --- 科技系统计算 (本地科研贡献) ---
function 计算本地科技账单(cid) {
    const 账单 = {};
    const 研发数据 = use科技系统().当前研发;
    const 内存满足率 = use计算机系统().内存满足率(cid); 

    if (!研发数据.科技ID) return { 科技账单: 账单, 本地科研进度贡献: 0 };

    const 科技 = 获取科技数据(研发数据.科技ID);
    const 配方分配 = use配方分配();
    const 能源模块 = use能源模块();
    
    // 只查询本殖民地的实验室
    const 科研分配 = 配方分配.查询建筑('ke_yan', cid);
    let 最大总产出 = 0;

    for (const 建筑id in 科研分配) {
        const 分配数据 = 科研分配[建筑id];
        if (分配数据.状态 === '运行' && 分配数据.数量 > 0) {
            const 建筑数据 = 获取建筑数据(建筑id);
            const 基础速度 = 建筑数据?.速度 || 1;
            let 能源满足率 = 1;
            if (建筑数据.能源类型 && 建筑数据.能源类型 !== '无') {
                能源满足率 = 能源模块.查询满足率(建筑数据.能源类型, cid);
            }
            最大总产出 += 分配数据.数量 * 基础速度 * 能源满足率 * 内存满足率;
        }
    }

    if (最大总产出 === 0) return { 科技账单: 账单, 本地科研进度贡献: 0 };

    const 理论每秒进度 = 科技.耗时 === 0 ? Infinity : 最大总产出 / 科技.耗时;

    // 👇 修复点4：检查当地科技包库存，计算实际进度，防止白嫖
    const 库存 = use库存();
    let 实际满足率 = 1;

    for (const 投入 of 科技.投入) {
        const 理论需求速率 = 理论每秒进度 * 投入.数量;
        if (理论需求速率 > 0) {
            // 注意：必须用查询库存去获取当地仓库的科技包
            const 当前库存 = 库存.查询库存(投入.id, cid) || 0;
            const 最大可支撑比例 = 当前库存 / 理论需求速率;
            if (最大可支撑比例 < 实际满足率) {
                实际满足率 = 最大可支撑比例;
            }
        }
    }
    
    实际满足率 = Math.min(实际满足率, 1);
    const 实际每秒进度 = 理论每秒进度 * 实际满足率;

    // 根据真实满足率计算本地消耗
    for (const 投入 of 科技.投入) {
        const 理论需求 = 理论每秒进度 * 投入.数量;
        const 实际消耗 = 实际每秒进度 * 投入.数量;
        账单[投入.id] = { 产出: 0, 消耗: 实际消耗, 需求: 理论需求, 净值: -实际消耗 };
    }
    return { 科技账单: 账单, 本地科研进度贡献: 实际每秒进度 };
}

// --- 配方系统计算 (本地化 + 丰度乘区) ---
function 计算本地配方账单(cid, 资源丰度) {
    const 配方分配 = use配方分配();
    const 临时速率表 = {};
    const 库存 = use库存();
    const 能源模块 = use能源模块();
    const 内存满足率 = use计算机系统().内存满足率(cid);

    for (const key in 获取所有物品列表()) {
        临时速率表[key] = { 产出: 0, 消耗: 0, 需求: 0, 净值: 0, 理论需求: 0, 理论产出: 0 };
    }

    // 1. 收集理论极值
    for (const 配方ID in 配方分配.查询全部(cid)) {
        const 分配情况 = 配方分配.查询全部(cid)[配方ID];
        const 当前配方 = 获取配方数据(配方ID);
        if (!当前配方 || 当前配方.时间 === 0) continue;

        // 🌟 行星资源丰度系统：如果是采集类，基础产量享受行星倍率加成
        let 当前配方丰度倍率 = 1;
        if (当前配方.类型 === '采集' && 当前配方.输出?.length > 0) {
            当前配方丰度倍率 = 资源丰度[当前配方.输出[0].id] ?? 1;
        }

        for (const 建筑ID in 分配情况) {
            if (分配情况[建筑ID].状态 !== '运行') continue;

            const 建筑 = 获取建筑数据(建筑ID);
            const 数量 = 分配情况[建筑ID].数量;
            let 能源满足率 = 1;
            if (建筑.能源类型 && 建筑.能源类型 !== '无') {
                能源满足率 = 能源模块.查询满足率(建筑.能源类型, cid);
            }

            const 机器实际最大速度 = 数量 * (建筑?.速度 || 0) * 能源满足率 * 内存满足率;
            const 每秒最大批次 = 机器实际最大速度 / 当前配方.时间;

            if (当前配方.输入) {
                for (const 原料 of 当前配方.输入) {
                    临时速率表[原料.id].理论需求 += 每秒最大批次 * 原料.数量;
                }
            }
            if (当前配方.输出) {
                for (const 产物 of 当前配方.输出) {
                    // 产出享受丰度加成
                    临时速率表[产物.id].理论产出 += 每秒最大批次 * 产物.数量 * 当前配方丰度倍率;
                }
            }
        }
    }

    // 2. 多轮迭代消除“虚假承诺” (逻辑与原来相同，只改了查库存的地方)
    const 迭代次数 = 8;
    for (let i = 0; i < 迭代次数; i++) {
        const 物品满足率表 = {};
        for (const 物品ID in 临时速率表) {
            const 数据 = 临时速率表[物品ID];
            const 当前库存 = 库存.查询库存(物品ID, cid) || 0; // 👈 必须传 cid
            const 预估产出 = (i === 0) ? 数据.理论产出 : 数据.产出;
            const 总供应能力 = 预估产出 + 当前库存;

            if (数据.理论需求 === 0) {
                物品满足率表[物品ID] = 1;
            } else {
                物品满足率表[物品ID] = Math.min(总供应能力 / 数据.理论需求, 1);
            }
        }

        for (const 物品ID in 临时速率表) {
            临时速率表[物品ID].产出 = 0;
            临时速率表[物品ID].消耗 = 0;
            临时速率表[物品ID].需求 = 0;
        }

        for (const 配方ID in 配方分配.查询全部(cid)) {
            const 分配情况 = 配方分配.查询全部(cid)[配方ID];
            const 当前配方 = 获取配方数据(配方ID);
            if (!当前配方 || 当前配方.时间 === 0) continue;

            let 当前配方丰度倍率 = 1;
            if (当前配方.类型 === '采集' && 当前配方.输出?.length > 0) {
                当前配方丰度倍率 = 资源丰度[当前配方.输出[0].id] ?? 1;
            }

            for (const 建筑ID in 分配情况) {
                if (分配情况[建筑ID].状态 !== '运行') continue;

                const 建筑 = 获取建筑数据(建筑ID);
                const 数量 = 分配情况[建筑ID].数量;
                let 能源满足率 = 1;
                if (建筑.能源类型 && 建筑.能源类型 !== '无') {
                    能源满足率 = 能源模块.查询满足率(建筑.能源类型, cid);
                }

                const 每秒最大批次 = (数量 * (建筑?.速度 || 0) * 能源满足率 * 内存满足率) / 当前配方.时间;

                let 最短板满足率 = 1;
                if (当前配方.输入) {
                    for (const 原料 of 当前配方.输入) {
                        const 该原料满足率 = 物品满足率表[原料.id] || 0;
                        if (该原料满足率 < 最短板满足率) 最短板满足率 = 该原料满足率;
                    }
                }

                const 实际每秒批次 = 每秒最大批次 * 最短板满足率;

                if (当前配方.输入) {
                    for (const 原料 of 当前配方.输入) {
                        临时速率表[原料.id].需求 += 每秒最大批次 * 原料.数量;
                        临时速率表[原料.id].消耗 += 实际每秒批次 * 原料.数量;
                    }
                }
                if (当前配方.输出) {
                    for (const 产物 of 当前配方.输出) {
                        临时速率表[产物.id].产出 += 实际每秒批次 * 产物.数量 * 当前配方丰度倍率;
                    }
                }
            }
        }
    }

    return 临时速率表;
}

// --- 能源系统计算 (本地独立电网 + 环境常数) ---
function 计算本地能源(cid, 环境) {
    const 消耗清单 = {};
    const 热能数据 = 结算热能(消耗清单, cid);
    const 蒸汽数据 = 结算蒸汽(消耗清单, 热能数据.满足率, cid);
    const 电力数据 = 结算电力(消耗清单, 蒸汽数据.满足率, cid, 环境); // 电力可能受风/光影响

    return {
        新能源数据: { 热能: 热能数据, 蒸汽: 蒸汽数据, 电力: 电力数据 },
        能源账单: 消耗清单
    };
}

function 计算指定能源总需求(能源类型, cid) {
    const 配方分配 = use配方分配();
    let 需求总计 = 0;
    const 机器列表 = 配方分配.查询指定能源类型建筑(能源类型, cid);
    for (const 建筑id in 机器列表) {
        const 机器 = 机器列表[建筑id];
        需求总计 += 机器.运行数量 * 机器.能耗;
    }
    return 需求总计;
}

function 计算指定能源总产出(产出物品ID, 上一级满足率, cid, 环境 = null) {
    const 内存满足率 = use计算机系统().内存满足率(cid);
    const 配方分配 = use配方分配();
    let 产出总计 = 0;
    
    for (const 配方ID in 配方分配.查询全部(cid)) {
        const 配方 = 获取配方数据(配方ID);
        const 目标输出 = 配方?.输出?.find(out => out.id === 产出物品ID);
        if (目标输出) {
            const 机器分配情况 = 配方分配.查询全部(cid)[配方ID];
            for (const 建筑ID in 机器分配情况) {
                const 状态 = 机器分配情况[建筑ID];
                if (状态.状态 === '运行') {
                    const 建筑 = 获取建筑数据(建筑ID);
                    const 机器速度 = 建筑?.速度 || 1;
                    
                    // 🌟 环境常数介入：如果是特殊的自然发电机
                    let 环境倍率 = 1;
                    if (环境) {
                        // 预留接口：若未来你加入了风力或太阳能建筑
                        // if (建筑ID === 物品ID.太阳能板) 环境倍率 = 环境.太阳能强度;
                        // if (建筑ID === 物品ID.风力机) 环境倍率 = 环境.风力等级;
                    }

                    const 每秒基准产出 = 目标输出.数量 / 配方.时间;
                    产出总计 += 状态.数量 * 机器速度 * 每秒基准产出 * 上一级满足率 * 内存满足率 * 环境倍率;
                }
            }
        }
    }
    return 产出总计;
}

function 结算热能(消耗清单, cid) {
    const 库存 = use库存();
    let 需求总热值 = 计算指定能源总需求('热能', cid);
    let 供应总热值 = 0;
    const 所有物品 = 获取所有物品列表();
    const 燃料列表 = Object.values(所有物品).filter(物品 => 物品.燃料 === true && 物品.热值 > 0);

    if (需求总热值 === 0) return { 供应: 0, 需求: 0, 满足率: 1, 负载率: 1 };

    let 剩余需求 = 需求总热值;
    for (const 燃料 of 燃料列表) {
        if (剩余需求 <= 0) break;
        const 燃料库存 = 库存.查询库存(燃料.id, cid) || 0; // 👈 必须是本地仓库的煤炭
        if (燃料库存 <= 0) continue;
        const 当前燃料能提供的总热值 = 燃料库存 * 燃料.热值;

        if (当前燃料能提供的总热值 >= 剩余需求) {
            const 需要消耗数量 = 剩余需求 / 燃料.热值;
            消耗清单[燃料.id] = { 产出: 0, 消耗: 需要消耗数量, 需求: 需要消耗数量, 净值: -需要消耗数量 };
            供应总热值 += 剩余需求;
            剩余需求 = 0;
        } else {
            消耗清单[燃料.id] = { 产出: 0, 消耗: 燃料库存, 需求: 剩余需求 / 燃料.热值, 净值: -燃料库存 };
            供应总热值 += 当前燃料能提供的总热值;
            剩余需求 -= 当前燃料能提供的总热值;
        }
    }

    const 热能满足率 = 需求总热值 === 0 ? 1 : Math.min(供应总热值 / 需求总热值, 1);
    
    // UI 显示用的产出速率
    let 燃料产出总热值速率 = 0;
    for (const 燃料 of 燃料列表) {
        const 燃料每秒产出数量 = 计算指定能源总产出(燃料.id, 1, cid);
        燃料产出总热值速率 += 燃料每秒产出数量 * 燃料.热值;
    }
    const 热能负载率 = 燃料产出总热值速率 === 0 ? (需求总热值 > 0 ? Infinity : 0) : 需求总热值 / 燃料产出总热值速率;

    return { 供应: 燃料产出总热值速率, 需求: 需求总热值, 满足率: 热能满足率, 负载率: 热能负载率 };
}

function 结算蒸汽(消耗清单, 热能满足率, cid) {
    const 库存 = use库存();
    const 需求总蒸汽 = 计算指定能源总需求('蒸汽', cid);
    const 蒸汽实时产出 = 计算指定能源总产出(物品ID.蒸汽, 热能满足率, cid);
    const 蒸汽库存 = 库存.查询库存(物品ID.蒸汽, cid) || 0;
    const 可用蒸汽总量 = 蒸汽实时产出 + 蒸汽库存;

    const 蒸汽满足率 = 需求总蒸汽 === 0 ? 1 : Math.min(可用蒸汽总量 / 需求总蒸汽, 1);
    const 蒸汽负载率 = 可用蒸汽总量 === 0 ? (需求总蒸汽 > 0 ? 1 : 0) : 需求总蒸汽 / 蒸汽实时产出;

    if (需求总蒸汽 > 0) {
        const 实际消耗 = Math.min(可用蒸汽总量, 需求总蒸汽);
        消耗清单[物品ID.蒸汽] = { 产出: 0, 消耗: 实际消耗, 需求: 需求总蒸汽, 净值: -实际消耗 };
    }
    return { 供应: 蒸汽实时产出, 需求: 需求总蒸汽, 满足率: 蒸汽满足率, 负载率: 蒸汽负载率 };
}

function 结算电力(消耗清单, 蒸汽满足率, cid, 环境) {
    const 需求总电力 = 计算指定能源总需求('电力', cid);
    const 供应总电力 = 计算指定能源总产出(物品ID.电力, 蒸汽满足率, cid, 环境);
    const 电力满足率 = 需求总电力 === 0 ? 1 : Math.min(供应总电力 / 需求总电力, 1);
    const 电力负载率 = 供应总电力 === 0 ? (需求总电力 > 0 ? 1 : 0) : 需求总电力 / 供应总电力;

    if (需求总电力 > 0) {
        const 实际消耗 = Math.min(供应总电力, 需求总电力);
        消耗清单[物品ID.电力] = { 产出: 0, 消耗: 实际消耗, 需求: 需求总电力, 净值: -实际消耗 };
    }
    return { 供应: 供应总电力, 需求: 需求总电力, 满足率: 电力满足率, 负载率: 电力负载率 };
}