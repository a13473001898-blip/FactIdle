function 速率数据模板() {
    return { 产出: 0, 消耗: 0, 需求: 0, 净值: 0, 理论需求: 0, 理论产出: 0 };
}

function 合并账单(总账单, 分账单) {
    for (const 物品id in 分账单) {
        if (!总账单[物品id]) 总账单[物品id] = 速率数据模板();
        const 单项 = 分账单[物品id];
        总账单[物品id].产出 += 单项.产出 || 0;
        总账单[物品id].消耗 += 单项.消耗 || 0;
        总账单[物品id].需求 += 单项.需求 || 0;
    }
}

// ==========================================
// 核心调度中心：统一算账
// ==========================================
export function 执行全局速率结算() {
    const 临时总账单 = {};
    for (const key in 获取所有物品列表()) {
        临时总账单[key] = 速率数据模板();
    }

    // 1. 结算能源系统 (算完立即写回 Store，供后面读取)
    const { 新能源数据, 能源账单 } = 计算全网能源();
    use能源模块().写入能源数据(新能源数据, 能源账单);

    // 2. 结算配方分配和科技系统
    const 配方账单 = 计算配方账单();
    const 科技账单 = 计算科技账单();

    // 3. 合并所有账单
    合并账单(临时总账单, 配方账单);
    合并账单(临时总账单, 能源账单);
    合并账单(临时总账单, 科技账单);

    // 4. 结算净值并覆盖全局速率
    for (const 物品id in 临时总账单) {
        const item = 临时总账单[物品id];
        item.净值 = item.产出 - item.消耗;
    }
    use全局速率().写入全局速率(临时总账单);
}

