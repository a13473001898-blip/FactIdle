function 速率数据模板() {
    return { 产出: 0, 消耗: 0, 需求: 0, 净值: 0, 理论需求: 0, 理论产出: 0 };
}

function 合并账单(总账单, 分账单) {
    for (const 物品id in 分账单) {
        if (!总账单[物品id]) 总账单[物品id] = 速率数据模板();
        const 单项 = 分账单[物品id];
        总账单[物品id].产出 += 单项.产出 || 0;
        总账单[物品id].消耗 += 单项.消耗 || 0;
        总账单[物品id].需求 += 单项.需求 || 0;
        // 理论值也可以选择性合并，供UI进度条参考
        总账单[物品id].理论需求 += 单项.理论需求 || 0;
        总账单[物品id].理论产出 += 单项.理论产出 || 0;
    }
}

// ==========================================
// 🌟 核心调度中心：多殖民地分布式结算
// ==========================================
export function 执行全局速率结算() {
    const 殖民地系统 = use殖民地系统();
    const 科技系统 = use科技系统();
    
    // 每次物理帧结算前，重置全球科技进度缓存
    科技系统.当前研发.每秒进度比例 = 0;

    // 大循环：遍历所有已发现的星球/基地
    for (const colony of 殖民地系统.列表) {
        const cid = colony.id;
        const 临时总账单 = {};
        for (const key in 获取所有物品列表()) {
            临时总账单[key] = 速率数据模板();
        }

        // 1. 结算本地能源 (传入环境常数，用于风力/太阳能计算)
        const { 新能源数据, 能源账单 } = 计算本地能源(cid, colony.环境);
        use能源模块().写入能源数据(cid, 新能源数据, 能源账单);

        // 2. 结算本地配方分配 (传入资源丰度，用于矿机加成)
        const 配方账单 = 计算本地配方账单(cid, colony.资源丰度);

        // 3. 结算本地科技系统 (计算该星球对全球科研的贡献)
        const { 科技账单, 本地科研进度贡献 } = 计算本地科技账单(cid);
        // 累加到全球总进度中
        科技系统.当前研发.每秒进度比例 += 本地科研进度贡献;

        // 4. 合并该殖民地的所有子账单
        合并账单(临时总账单, 配方账单);
        合并账单(临时总账单, 能源账单);
        合并账单(临时总账单, 科技账单);

        // 5. 结算该星球的最终净值，并写入速率Store
        for (const 物品id in 临时总账单) {
            const item = 临时总账单[物品id];
            item.净值 = item.产出 - item.消耗;
        }
        use全局速率().写入殖民地速率(cid, 临时总账单);
    }
}

