import { defineStore } from 'pinia'
import { 获取建筑数据, 获取科技数据,科技配置 } from "../pei_zhi_shu_ju.js";
import { use库存 } from '@/stores/ku_cun.js';
import { use配方分配 } from '@/stores/pei_fang_fen_pei.js';
import { use全局速率 } from '@/stores/su_lv.js'


export const use科技系统 = defineStore('ke_ji_xi_tong', {
    state: () => ({
        已解锁科技: ['chu_shi_ke_ji_t'],
        当前研发: {
            科技ID: null,      // 当前正在研究的科技
            已完成比例: 0,     // 当前的进度数值
            每秒进度比例: 0    // 给 UI 进度条显示速率用的缓存值
        }
    }),

    getters: {
        已解锁配方: (state) => {
            const 配方Set = new Set();
            for (const techId of state.已解锁科技) {
                const 科技 = 获取科技数据(techId);
                if (科技 && 科技.解锁配方) {
                    科技.解锁配方.forEach(id => 配方Set.add(id));
                }
            }
            return Array.from(配方Set);
        },

        可研发科技列表: (state) => {
            const 已解锁 = state.已解锁科技 || [];
            return Object.values(科技配置).filter(科技 => {
                // 1. 已经解锁的就不显示了
                if (已解锁.includes(科技.id)) return false;
                // 2. 前置科技没解锁的不显示
                const 前置满足 = 科技.前置科技.every(前置id => 已解锁.includes(前置id));
                return 前置满足;
            })
        },
    },

    actions: {
        切换当前研发科技(科技ID) {
            const 全局速率 = use全局速率()
            if (this.当前研发.科技ID === 科技ID) return;

            this.当前研发.科技ID = 科技ID;
            this.当前研发.已完成比例 = 0;
            全局速率.更新全局速率();
        },

        结算科研最大预期(临时速率表, 能源数据) {
            const 配方分配 = use配方分配()
            const 库存 = use库存()
            const 研发数据 = this.当前研发;
            const 科技 = 获取科技数据(研发数据.科技ID)

            // TODO 1: 检查 研发数据.科技ID 是否存在，不存在则将 每秒进度比例 设为 0 并 return
            if (!研发数据.科技ID) {
                研发数据.每秒进度比例 = 0
                return
            }

            let 材料充足 = true;
            for (const 投入 of 科技.投入) {
                if ((库存.数据[投入.id] || 0) <= 0) {
                    材料充足 = false;
                    break; // 只要有一种科技包耗尽，立即停工
                }
            }

            // TODO 2: 获取 配方ID.研究 下分配的实验室总数、运行状态。如果没运行，进度设为 0 并 return
            const 科研分配 = 配方分配.查询建筑('lab_run');
            let 总运行建筑 = {};
            let 有建筑在运行 = false;
            for (const 建筑id in 科研分配) {
                const 分配数据 = 科研分配[建筑id];
                if (分配数据.状态 === '运行') {
                    总运行建筑[建筑id] = 分配数据.数量;
                    有建筑在运行 = true;
                }
            }
            if (!有建筑在运行) {
                研发数据.每秒进度比例 = 0;
                return;
            }

            // TODO 3: 获取实验室的 基础速度 和 能源数据中的 供电率，计算出“实际总产出速度”
            let 最大总产出 = 0
            for (const 建筑id in 总运行建筑) {
                const 数量 = 总运行建筑[建筑id]
                const 建筑数据 = 获取建筑数据(建筑id)
                const 基础速度 = 获取建筑数据(建筑id)?.速度 || 1
                let 满足率 = 1
                if (建筑数据.能源类型 && 建筑数据.能源类型 !== '无') {
                    满足率 = 能源数据[建筑数据.能源类型]?.满足率 || 0;
                }
                const 建筑产出 = 数量 * 基础速度 * 满足率;

                最大总产出 += 建筑产出
            }

            if (最大总产出 === 0) {
                研发数据.每秒进度比例 = 0;
                return;
            }

            // TODO 4: 计算 每秒最大进度比例 = 实际总产出速度 / 科技.总耗时，存入 研发数据.每秒进度比例


            const 每秒最大进度比例 = 科技.耗时 === 0
                ? Infinity
                : 最大总产出 / 科技.耗时
            研发数据.每秒进度比例 = 每秒最大进度比例

            // TODO 5: 遍历科技的 投入 数组，根据 每秒最大进度比例 计算出每种物资的每秒预期消耗量，累加到 临时速率表[投入.id].消耗 中
            for (const 投入 of 科技.投入) {

                // 1. 防御性代码：如果全局临时速率表里还没建这个物品的账本，先初始化一下
                if (!临时速率表[投入.id]) {
                    临时速率表[投入.id] = { 产出: 0, 消耗: 0, 净值: 0 };
                }

                // 消耗量 = 每秒跑百分之几的进度 * 这个科技总共需要多少个该物资
                临时速率表[投入.id].消耗 += 每秒最大进度比例 * 投入.数量;
            }


        },

        推进实际科研进度(过去的时间秒) {
            const 全局速率 = use全局速率()
            const 库存 = use库存()
            const 研发数据 = this.当前研发;

            if (!研发数据.科技ID || 研发数据.每秒进度比例 <= 0) return;

            const 科技 = 获取科技数据(研发数据.科技ID);

            // 1. 寻找“木桶的最短板”（计算所有所需物资的最小满足比例）
            let 最小满足比例 = 1;

            for (const 投入 of 科技.投入) {
                // 这一帧理论上最大需要吃掉多少这个物资？
                const 理论最大消耗 = 投入.数量 * 研发数据.每秒进度比例 * 过去的时间秒;

                if (理论最大消耗 > 0) {
                    const 当前库存 = 库存.数据[投入.id] || 0;

                    if (当前库存 <= 0) {
                        最小满足比例 = 0; // 彻底断货了，比例归零
                        break;
                    }

                    // 算算库存够支撑百分之几的最大消耗
                    const 当前满足比例 = 当前库存 / 理论最大消耗;
                    if (当前满足比例 < 最小满足比例) {
                        最小满足比例 = 当前满足比例;
                    }
                }
            }

            // 如果连一点点材料都凑不齐，完全卡死，就不推进进度了
            if (最小满足比例 <= 0) return;

            // 2. 根据找出的最短板，按比例真实扣除物资

            // 3. 按比例真实增加科研进度
            研发数据.已完成比例 += 研发数据.每秒进度比例 * 过去的时间秒 * 最小满足比例;

            // 4. 判断是否研发完成 (1 代表 100%)
            if (研发数据.已完成比例 >= 1) {
                if (!this.已解锁科技.includes(科技.id)) {
                    this.已解锁科技.push(科技.id);
                }

                console.log(`恭喜！科技 [${科技.名称}] 研发完成！`);

                // 还原状态
                研发数据.科技ID = null;
                研发数据.已完成比例 = 0;
                研发数据.每秒进度比例 = 0;

                // 科技完成后，能源占用变了，解锁配方也变了，必须刷新全局速率
                全局速率.更新全局速率();
            }
        }

    }
})