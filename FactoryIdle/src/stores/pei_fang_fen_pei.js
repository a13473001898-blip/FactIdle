import { defineStore } from 'pinia';
import { use库存 } from '@/stores/ku_cun.js';
import { 获取建筑数据, 获取所有物品列表, 获取配方数据 } from '@/pei_zhi_shu_ju.js';
import { use能源模块 } from './neng_yuan_xi_tong';
import { use全局速率 } from '@/stores/su_lv.js'


function 配方分配数据模板(状态 = '运行') {
    return {
        数量: 0,
        状态: 状态, //默认状态为运行
    }
}

export const use配方分配 = defineStore('pei_fang_fen_pei', {
    state: () => ({
        数据: {}
    }),

    actions: {
        // ================= 查询接口 =================
        查询全部() {
            return this.数据
        },

        查询建筑(配方id) {
            const 建筑列表 = this.数据[配方id]
            if (!建筑列表) return {}
            return 建筑列表
        },

        查询分配数量(配方id, 建筑id) {
            const 配方数据 = this.数据[配方id]
            if (!建筑id) return 配方数据 || {}
            return 配方数据?.[建筑id]?.数量 || 0
        },

        查询建筑状态(配方id, 建筑id) {
            return this.数据[配方id]?.[建筑id]?.状态 || '运行';
        },

        查询指定能源类型建筑(能源类型) {
            const 结果 = {}
            for (const 配方ID in this.数据) {
                for (const 建筑ID in this.数据[配方ID]) {
                    const 建筑数据 = 获取建筑数据(建筑ID)
                    if (建筑数据 && 建筑数据.能源类型 === 能源类型) {
                        const 分配状态 = this.数据[配方ID][建筑ID]
                        if (!结果[建筑ID]) {
                            结果[建筑ID] = {
                                运行数量: 0,
                                停止数量: 0,
                                能耗: 建筑数据.能耗 || 0
                            }
                        }
                        if (分配状态.状态 === '运行') {
                            结果[建筑ID].运行数量 += 分配状态.数量
                        } else {
                            结果[建筑ID].停止数量 += 分配状态.数量
                        }
                    }
                }
            }
            return 结果
        },
        获取配方账单() {
            const 临时速率表 = {};
            const 库存 = use库存();
            const 能源模块 = use能源模块();
            const 全局算力满足率 = 1; // 预留的计算机系统钩子

            // 0. 初始化
            for (const key in 获取所有物品列表()) {
                临时速率表[key] = { 产出: 0, 消耗: 0, 需求: 0, 净值: 0, 理论需求: 0, 理论产出: 0 };
            }

            // 1. 收集理论极值 (所有人画大饼)
            for (const 配方ID in this.数据) {
                const 分配情况 = this.数据[配方ID];
                const 当前配方 = 获取配方数据(配方ID);
                if (!当前配方 || 当前配方.时间 === 0) continue;

                for (const 建筑ID in 分配情况) {
                    if (分配情况[建筑ID].状态 !== '运行') continue;

                    const 建筑 = 获取建筑数据(建筑ID);
                    const 数量 = 分配情况[建筑ID].数量;
                    const 基础速度 = 建筑?.速度 || 0;

                    let 能源满足率 = 1;
                    if (建筑.能源类型 && 建筑.能源类型 !== '无') {
                        能源满足率 = 能源模块.数据[建筑.能源类型]?.满足率 || 0;
                    }

                    // 机器当前的理论物理极限
                    const 机器实际最大速度 = 数量 * 基础速度 * 能源满足率 * 全局算力满足率;
                    const 每秒最大批次 = 机器实际最大速度 / 当前配方.时间;

                    if (当前配方.输入) {
                        for (const 原料 of 当前配方.输入) {
                            临时速率表[原料.id].理论需求 += 每秒最大批次 * 原料.数量;
                        }
                    }
                    if (当前配方.输出) {
                        for (const 产物 of 当前配方.输出) {
                            临时速率表[产物.id].理论产出 += 每秒最大批次 * 产物.数量;
                        }
                    }
                }
            }

            // ==========================================
            // 【核心修复】：多轮迭代消除“虚假承诺” (4次循环即可击穿大部分产业链)
            // ==========================================
            const 迭代次数 = 8;
            for (let i = 0; i < 迭代次数; i++) {

                // A. 算出目前的满足率
                const 物品满足率表 = {};
                for (const 物品ID in 临时速率表) {
                    const 数据 = 临时速率表[物品ID];
                    const 当前库存 = 库存.查询库存(物品ID) || 0;

                    // 【关键】：第一轮用吹牛的理论值，后续轮次用上一轮挤完水分的真实产出
                    const 预估产出 = (i === 0) ? 数据.理论产出 : 数据.产出;
                    const 总供应能力 = 预估产出 + 当前库存;

                    if (数据.理论需求 === 0) {
                        物品满足率表[物品ID] = 1;
                    } else {
                        物品满足率表[物品ID] = Math.min(总供应能力 / 数据.理论需求, 1);
                    }
                }

                // B. 重置本轮账本，准备重新结算
                for (const 物品ID in 临时速率表) {
                    临时速率表[物品ID].产出 = 0;
                    临时速率表[物品ID].消耗 = 0;
                    临时速率表[物品ID].需求 = 0;
                }

                // C. 根据新的满足率，挤掉水分，计算真实产耗
                for (const 配方ID in this.数据) {
                    const 分配情况 = this.数据[配方ID];
                    const 当前配方 = 获取配方数据(配方ID);
                    if (!当前配方 || 当前配方.时间 === 0) continue;

                    for (const 建筑ID in 分配情况) {
                        if (分配情况[建筑ID].状态 !== '运行') continue;

                        const 建筑 = 获取建筑数据(建筑ID);
                        const 数量 = 分配情况[建筑ID].数量;
                        let 能源满足率 = 1;
                        if (建筑.能源类型 && 建筑.能源类型 !== '无') {
                            能源满足率 = 能源模块.数据[建筑.能源类型]?.满足率 || 0;
                        }

                        const 每秒最大批次 = (数量 * (建筑?.速度 || 0) * 能源满足率 * 全局算力满足率) / 当前配方.时间;

                        // 找木桶的最短板
                        let 最短板满足率 = 1;
                        if (当前配方.输入) {
                            for (const 原料 of 当前配方.输入) {
                                const 该原料满足率 = 物品满足率表[原料.id] || 0;
                                if (该原料满足率 < 最短板满足率) {
                                    最短板满足率 = 该原料满足率;
                                }
                            }
                        }

                        const 实际每秒批次 = 每秒最大批次 * 最短板满足率;

                        // 记账
                        if (当前配方.输入) {
                            for (const 原料 of 当前配方.输入) {
                                临时速率表[原料.id].需求 += 每秒最大批次 * 原料.数量; // UI 依然显示红色的需求缺口
                                临时速率表[原料.id].消耗 += 实际每秒批次 * 原料.数量; // 真实消耗被严格压制
                            }
                        }
                        if (当前配方.输出) {
                            for (const 产物 of 当前配方.输出) {
                                临时速率表[产物.id].产出 += 实际每秒批次 * 产物.数量;
                            }
                        }
                    }
                }
            }

            // 4. 结算最终净值
            for (const key in 临时速率表) {
                const item = 临时速率表[key];
                item.净值 = item.产出 - item.消耗;
            }

            return 临时速率表;
        },
        // ================= 操作接口 =================
        初始化配方分配数据(配方id, 建筑id) {
            if (!this.数据[配方id]) {
                this.数据[配方id] = {}
            }
            if (!this.数据[配方id][建筑id]) {
                this.数据[配方id][建筑id] = 配方分配数据模板()
            }
        },

        增加分配数量(配方id, 建筑id, 数量) {
            const 全局速率 = use全局速率()
            const 库存 = use库存()
            const 当前库存 = 库存.查询库存(建筑id) || 0;
            const 实际增加数量 = Math.min(数量, 当前库存);
            if (实际增加数量 <= 0) return;
            if (!库存.库存减少(建筑id, 实际增加数量)) return;
            this.初始化配方分配数据(配方id, 建筑id);
            this.数据[配方id][建筑id].数量 += 实际增加数量;
            全局速率.更新全局速率()
        },

        减少分配数量(配方id, 建筑id, 数量) {
            const 全局速率 = use全局速率()
            const 库存 = use库存()
            const 当前数量 = this.查询分配数量(配方id, 建筑id);
            const 实际减少数量 = Math.min(数量, 当前数量)
            if (实际减少数量 <= 0) return

            this.数据[配方id][建筑id].数量 -= 实际减少数量
            库存.库存增加(建筑id, 实际减少数量)



            if (this.数据[配方id][建筑id].数量 <= 0) {
                delete this.数据[配方id][建筑id];
            }
            全局速率.更新全局速率()
        },

        切换建筑状态(配方id, 建筑id) {
            const 全局速率 = use全局速率()
            const 建筑数据 = this.数据?.[配方id]?.[建筑id]
            if (!建筑数据) return
            if (建筑数据.状态 === '运行') 建筑数据.状态 = '停止'
            else {
                建筑数据.状态 = '运行'
            }
            全局速率.更新全局速率()
        },


    }
})