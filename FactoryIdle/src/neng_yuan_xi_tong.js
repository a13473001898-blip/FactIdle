import { 获取建筑数据, 获取所有物品列表, 获取物品数据, 获取配方数据, 配置数据 } from "./pei_zhi_shu_ju";
import { 查询库存, 查询配方分配, 查询配方分配建筑的能源类型, 查询配方分配数量 } from "./dong_tai_shu_ju.js"

const 能源数据 = {
    '热能': {
        '需求' : 0,
        '供应' : 0,
        '供应率' : 1
    },

    '蒸汽': {
        '需求' : 0,
        '供应' : 0,
        '供应率' : 1
    },

    '电力': {
        '需求' : 0,
        '供应' : 0,
        '供应率' : 1
    }
}


function 计算指定能源总需求(能源类型) {
    let 需求总计 = 0;
    const 机器列表 = 查询配方分配建筑的能源类型(能源类型);
    for (const 建筑id in 机器列表) {
        const 机器 = 机器列表[建筑id];
        需求总计 += 机器.运行数量 * 机器.能耗;
    }
    return 需求总计;
}

function 计算指定能源总产出(产出物品ID, 上一级供应率) {
    let 产出总计 = 0;

    // 遍历所有配方分配
    for (const 配方ID in 查询配方分配()) {
        const 配方 = 获取配方数据(配方ID);

        // 找找这个配方的输出里，有没有我们想要的能源（比如 'zheng_qi'）
        const 目标输出 = 配方?.输出?.find(out => out.id === 产出物品ID);

        if (目标输出) {
            // 这个配方能产出我们要的能源！算算分配了多少机器
            const 机器分配情况 = 查询配方分配()[配方ID];
            for (const 建筑ID in 机器分配情况) {
                const 状态 = 机器分配情况[建筑ID];
                if (状态.状态 === '运行') {
                    const 建筑 = 获取建筑数据(建筑ID);
                    const 机器速度 = 建筑?.速度 || 1;
                    const 每秒基准产出 = 目标输出.数量 / 配方.时间;

                    // 核心公式：数量 * 速度 * 每秒基准产出 * 燃料/蒸汽的供应率
                    产出总计 += 状态.数量 * 机器速度 * 每秒基准产出 * 上一级供应率;
                }
            }
        }
    }
    return 产出总计;
}

export function 结算热能() {
    let 需求总热值 = 计算指定能源总需求('热能');
    let 供应总热值 = 0;
    let 消耗清单 = {};

    // 如果没有热能需求，跳过计算
    if (需求总热值 === 0) {
        能源数据['热能'].需求 = 0;
        能源数据['热能'].供应 = 0;
        能源数据['热能'].供应率 = 1
        return 消耗清单 ;
    }

    // 2. 找出所有合法的燃料物品
    const 所有物品 = 获取所有物品列表();
    const 燃料列表 = Object.values(所有物品).filter(物品 => 物品.燃料 === true && 物品.热值 > 0);

    // TODO: 如果想设置燃烧优先级（比如先烧木头再烧煤），可以在这里对 燃料列表 进行 sort 排序

    // 3. 开始依次燃烧，填补需求
    let 剩余需求 = 需求总热值;

    for (const 燃料 of 燃料列表) {
        if (剩余需求 <= 0) break; // 需求填满之后停止计算

        const 燃料库存 = 查询库存(燃料.id) || 0;
        if (燃料库存 <= 0) continue; // 这个燃料用光了，换下一种

        const 当前燃料能提供的总热值 = 燃料库存 * 燃料.热值;

        if (当前燃料能提供的总热值 >= 剩余需求) {
            // 情况A：当前这种燃料足够填满剩下的坑
            const 需要消耗数量 = 剩余需求 / 燃料.热值;
            消耗清单[燃料.id] = 需要消耗数量;
            供应总热值 += 剩余需求;
            剩余需求 = 0;
        } else {
            // 情况B：当前这种燃料不够，全搭进去！
            消耗清单[燃料.id] = 燃料库存;
            供应总热值 += 当前燃料能提供的总热值;
            剩余需求 -= 当前燃料能提供的总热值;
        }
    }

    // 4. 计算最终的供应率
    const 热能供应率 = 供应总热值 / 需求总热值;

    // 5. 更新数据
        能源数据['热能'].需求 = 需求总热值;
        能源数据['热能'].供应 = 供应总热值;
        能源数据['热能'].供应率 = 热能供应率;
    
    return 消耗清单
}

export function 结算蒸汽() {
    // 1. 算需求
    const 需求总蒸汽 = 计算指定能源总需求('蒸汽');

    // 2. 算供应 (依赖上一级的 热能供应率)
    const 供应总蒸汽 = 计算指定能源总产出('zheng_qi', 能源数据['热能'].供应率);

    // 3. 算供应率 (如果需求为0，说明没人用蒸汽，供应率默认1)
    const 蒸汽供应率 = 需求总蒸汽 === 0 ? 1 : Math.min(供应总蒸汽 / 需求总蒸汽, 1);

    // 4. 更新数据
        能源数据['蒸汽'].需求 = 需求总蒸汽;
        能源数据['蒸汽'].供应 = 供应总蒸汽;
        能源数据['蒸汽'].供应率 = 蒸汽供应率;
}

export function 结算电力() {
    // 跟上面一模一样
    const 需求总电力 = 计算指定能源总需求('电力');
    const 供应总电力 = 计算指定能源总产出('dian_li', 能源数据['蒸汽'].供应率);

    const 电力供应率 = 需求总电力 === 0 ? 1 : Math.min(供应总电力 / 需求总电力, 1);

        能源数据['电力'].需求 = 需求总电力;
        能源数据['电力'].供应 = 供应总电力;
        能源数据['电力'].供应率 = 电力供应率;
}

export function 运行能源系统() {
    const 消耗账单 = 结算热能();
    结算蒸汽();
    结算电力();

    return {
        能源数据: {
            '热能': {...能源数据['热能']},
            '蒸汽': {...能源数据['蒸汽']},
            '电力': {...能源数据['电力']}
        }, 
        消耗清单: 消耗账单
    };
}