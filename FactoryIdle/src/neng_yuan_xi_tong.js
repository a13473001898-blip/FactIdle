import { 物品ID, 获取建筑数据, 获取所有物品列表, 获取物品数据, 获取配方数据, 配置数据 } from "./pei_zhi_shu_ju";
import { 查询库存, 查询配方分配, 查询配方分配建筑的能源类型, 查询配方分配数量, 游戏数据 } from "./dong_tai_shu_ju.js"


function 计算指定能源总需求(能源类型) {
    let 需求总计 = 0;
    const 机器列表 = 查询配方分配建筑的能源类型(能源类型);
    for (const 建筑id in 机器列表) {
        const 机器 = 机器列表[建筑id];
        需求总计 += 机器.运行数量 * 机器.能耗;
    }
    return 需求总计;
}

function 计算指定能源总产出(产出物品ID, 上一级负载率) {
    let 产出总计 = 0;

    // 遍历所有配方分配
    for (const 配方ID in 查询配方分配()) {
        const 配方 = 获取配方数据(配方ID);

        // 找找这个配方的输出里，有没有我们想要的能源（比如 'zheng_qi'）
        const 目标输出 = 配方?.输出?.find(out => out.id === 产出物品ID);

        if (目标输出) {
            // 这个配方能产出我们要的能源！算算分配了多少机器
            const 机器分配情况 = 查询配方分配()[配方ID];
            for (const 建筑ID in 机器分配情况) {
                const 状态 = 机器分配情况[建筑ID];
                if (状态.状态 === '运行') {
                    const 建筑 = 获取建筑数据(建筑ID);
                    const 机器速度 = 建筑?.速度 || 1;
                    const 每秒基准产出 = 目标输出.数量 / 配方.时间;

                    // 核心公式：数量 * 速度 * 每秒基准产出 * 上一级能源负载率
                    产出总计 += 状态.数量 * 机器速度 * 每秒基准产出 * 上一级负载率;
                }
            }
        }
    }
    return 产出总计;
}

export function 结算热能(消耗清单) {
    let 需求总热值 = 计算指定能源总需求('热能');
    let 供应总热值 = 0;

    const 所有物品 = 获取所有物品列表();
    const 燃料列表 = Object.values(所有物品).filter(物品 => 物品.燃料 === true && 物品.热值 > 0);

    // 如果没有热能需求，跳过计算
    if (需求总热值 === 0) {
        return {
        供应: 0,
        需求: 0,
        负载率: 1
        };
    }

    // 2. 找出所有合法的燃料物品


    // TODO: 如果想设置燃烧优先级（比如先烧木头再烧煤），可以在这里对 燃料列表 进行 sort 排序

    // 3. 开始依次燃烧，填补需求
    let 剩余需求 = 需求总热值;

    for (const 燃料 of 燃料列表) {
        if (剩余需求 <= 0) break; // 需求填满之后停止计算

        const 燃料库存 = 查询库存(燃料.id) || 0;
        if (燃料库存 <= 0) continue; // 这个燃料用光了，换下一种

        const 当前燃料能提供的总热值 = 燃料库存 * 燃料.热值;

        if (当前燃料能提供的总热值 >= 剩余需求) {
            // 情况A：当前这种燃料足够填满剩下的坑
            const 需要消耗数量 = 剩余需求 / 燃料.热值;
            消耗清单[燃料.id] = 需要消耗数量;
            供应总热值 += 剩余需求;
            剩余需求 = 0;
        } else {
            // 情况B：当前这种燃料不够，全搭进去！
            消耗清单[燃料.id] = 燃料库存;
            供应总热值 += 当前燃料能提供的总热值;
            剩余需求 -= 当前燃料能提供的总热值;
        }
    }

    // 4. 计算最终的负载率
    const 热能负载率 = 供应总热值 / 需求总热值
    const UI显示供应值 = 计算热能速率(燃料列表);

    return {
        供应: UI显示供应值,
        需求: 需求总热值,
        负载率: 热能负载率
    }
}

export function 结算蒸汽(消耗清单) {
    // 1. 算需求
    const 需求总蒸汽 = 计算指定能源总需求('蒸汽');


    // 2. 算供应 (依赖上一级的 热能负载率)
    const 蒸汽实时产出 = 计算指定能源总产出(物品ID.蒸汽, 游戏数据.能源系统['热能'].负载率);
    const 蒸汽库存 = 查询库存(物品ID.蒸汽) || 0;
    const 可用蒸汽总量 = 蒸汽实时产出 + 蒸汽库存;

    // 3. 算负载率 (如果需求为0，说明没人用蒸汽，负载率默认1)
    const 蒸汽负载率 = 需求总蒸汽 === 0 ? 1 : Math.min(可用蒸汽总量 / 需求总蒸汽, 1)

    if (需求总蒸汽 > 0) {
        消耗清单[物品ID.蒸汽] = Math.min(可用蒸汽总量, 需求总蒸汽);
    }

    return {
        供应: 蒸汽实时产出,
        需求: 需求总蒸汽,
        负载率: 蒸汽负载率
    }
}

export function 结算电力(消耗清单) {
    // 跟上面一模一样
    const 需求总电力 = 计算指定能源总需求('电力');
    const 供应总电力 = 计算指定能源总产出(物品ID.电力, 游戏数据.能源系统['蒸汽'].负载率);

    const 电力负载率 = 需求总电力 === 0 ? 1 : Math.min(供应总电力 / 需求总电力, 1);

    if (需求总电力 > 0) {
        消耗清单[物品ID.电力] = Math.min(供应总电力, 需求总电力);
    }
    return {
        供应: 供应总电力,
        需求: 需求总电力,
        负载率: 电力负载率
    }
}

export function 运行能源系统() {
    let 当前帧消耗清单 = {}

    游戏数据.能源系统['热能'] = 结算热能(当前帧消耗清单);
    游戏数据.能源系统['蒸汽'] = 结算蒸汽(当前帧消耗清单);
    游戏数据.能源系统['电力'] = 结算电力(当前帧消耗清单);

    return {
        消耗清单: 当前帧消耗清单
    };
}



function 计算热能速率(燃料列表) {
    let 燃料产出总热值速率 = 0;
    for (const 燃料 of 燃料列表) {
        const 燃料每秒产出数量 = 计算指定能源总产出(燃料.id, 1);
        燃料产出总热值速率 += 燃料每秒产出数量 * 燃料.热值;

    }
    return 燃料产出总热值速率
}